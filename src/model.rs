//! Model metadata and the per-batch data flow built on it.
//!
//! At startup the server inspects the model's inputs and outputs and builds a
//! [`ModelPlan`]. Per batch the plan then:
//!
//! 1. validates each request's [`Inputs`] ([`ModelPlan::prepare_request`]),
//!    so a malformed request fails alone;
//! 2. stacks the requests into batched input tensors, padding dynamic
//!    dimensions to the longest request and partial batches to a fixed model
//!    batch size ([`ModelPlan::assemble`]);
//! 3. splits every selected output back into per-request tensors, dropping
//!    padded rows and cutting padded positions back to each request's own
//!    length ([`ModelPlan::split_outputs`]).

use crate::config::{OutputSpec, ServerConfig};
use crate::io::{Inputs, Outputs};
use crate::split::{PaddedDim, Split, SplitContext, split_batch_axis, split_by_batch_index};
use crate::tensor::{Element, ElementType, Tensor, map_tensor, visit_tensor, with_element_type};
use anyhow::{Context, Result};
use ndarray::{ArrayD, Axis, IxDyn, Slice};
use ort::session::Session;
use ort::value::{DynValue, ValueType};
use std::collections::{HashMap, HashSet};
use std::sync::Arc;

/// A dimension of a model input or output as declared in the model.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Dim {
    Fixed(usize),
    /// Dynamic, identified by its key: the symbolic name, or
    /// `"<tensor>[<axis>]"` when it has none.
    Dynamic(Arc<str>),
}

/// Declared type and shape of a model input or output.
struct Declared {
    /// `None` if the element type is not supported (or not a tensor).
    dtype: Option<ElementType>,
    /// Human-readable type, for errors.
    type_name: String,
    /// `None` when the model declares no shape (reported as rank 0).
    dims: Option<Vec<Dim>>,
    /// Raw symbolic names, parallel to `dims`.
    symbols: Vec<String>,
}

fn dim_key(tensor: &str, axis: usize) -> Arc<str> {
    format!("{tensor}[{axis}]").into()
}

fn declared(name: &str, value_type: &ValueType) -> Declared {
    match value_type {
        ValueType::Tensor {
            ty,
            shape,
            dimension_symbols,
        } => {
            let symbols: Vec<String> = dimension_symbols.iter().cloned().collect();
            let dims = (!shape.is_empty()).then(|| {
                shape
                    .iter()
                    .enumerate()
                    .map(|(axis, &d)| {
                        if d >= 0 {
                            Dim::Fixed(d as usize)
                        } else {
                            match symbols.get(axis).filter(|s| !s.is_empty()) {
                                Some(symbol) => Dim::Dynamic(symbol.as_str().into()),
                                None => Dim::Dynamic(dim_key(name, axis)),
                            }
                        }
                    })
                    .collect()
            });
            Declared {
                dtype: ElementType::from_ort(*ty),
                type_name: format!("tensor of {ty}"),
                dims,
                symbols,
            }
        }
        other => Declared {
            dtype: None,
            type_name: format!("{other:?}"),
            dims: None,
            symbols: Vec::new(),
        },
    }
}

/// Whether a symbolic dimension name was generated by an exporter rather than
/// chosen by the model author, so that two different names may still denote
/// the same dimension.
fn is_generated_symbol(symbol: &str) -> bool {
    symbol.is_empty()
        || symbol == "?"
        || symbol.starts_with("unk__")
        || symbol.contains("dynamic_axes")
}

struct InputPlan {
    name: Arc<str>,
    dtype: Option<ElementType>,
    type_name: String,
    batched: bool,
    /// Per-request dims (without the batch axis) for batched inputs; `None`
    /// if the model declares no shape.
    dims: Option<Vec<Dim>>,
    pad_value: f64,
}

impl InputPlan {
    /// Per-request dims of a concrete per-request tensor.
    fn request_dims(&self, tensor: &Tensor) -> Vec<Dim> {
        match &self.dims {
            Some(dims) => dims.clone(),
            None => (1..=tensor.ndim())
                .map(|axis| Dim::Dynamic(dim_key(&self.name, axis)))
                .collect(),
        }
    }
}

/// Whether an output axis holds positions of a padded input dimension.
#[derive(Clone, Debug, PartialEq, Eq)]
enum AxisRole {
    /// Follows the input dimension with this key: cut back per request.
    Crop(Arc<str>),
    /// Never padded.
    Independent,
    /// Unknown: an error if its length equals a dimension padded in the batch.
    Ambiguous,
}

enum SplitPlan {
    BatchAxis,
    BatchIndex {
        source: Option<Arc<str>>,
        column: Option<usize>,
    },
    Custom(crate::split::SplitFn),
}

struct OutputPlan {
    name: Arc<str>,
    split: SplitPlan,
    /// Roles of the axes of the batched output, by axis. Axes not listed are
    /// [`AxisRole::Ambiguous`].
    roles: HashMap<usize, AxisRole>,
    /// Why this output can never be split per request, if it cannot.
    problem: Option<String>,
}

impl OutputPlan {
    fn role(&self, axis: usize) -> AxisRole {
        self.roles
            .get(&axis)
            .cloned()
            .unwrap_or(AxisRole::Ambiguous)
    }
}

/// How a model's inputs are batched and its outputs split per request.
pub(crate) struct ModelPlan {
    inputs: Vec<InputPlan>,
    default_input: Arc<str>,
    batch_size: Option<usize>,
    outputs: Vec<OutputPlan>,
    /// Outputs the worker has to read: selected ones and batch index sources.
    needed_outputs: Vec<Arc<str>>,
}

/// A validated request: one tensor per model input, in model input order.
pub(crate) struct PreparedRequest {
    tensors: Vec<Tensor>,
}

/// Batched input tensors plus what is needed to split the outputs.
pub(crate) struct AssembledBatch {
    /// Batched tensors, in model input order.
    pub(crate) tensors: Vec<(Arc<str>, Tensor)>,
    num_requests: usize,
    rows: usize,
    padded_dims: Vec<PaddedDim>,
}

impl ModelPlan {
    /// Inspect the model and the config.
    ///
    /// # Errors
    ///
    /// Returns an error for a model or config that can never be served: no
    /// inputs, conflicting fixed batch sizes, input/crop options that do not
    /// match the model, or a selected output with a dynamic axis whose
    /// relation to the padded input dimensions is unknown. Other problems
    /// specific to one output are reported when that output is used instead.
    pub(crate) fn new(session: &Session, config: &ServerConfig) -> Result<Self> {
        let mut inputs = Vec::new();
        let mut fixed_batch: Option<(usize, Arc<str>)> = None;
        let mut batch_symbols: HashSet<String> = HashSet::new();

        for outlet in session.inputs() {
            let name: Arc<str> = outlet.name().into();
            let decl = declared(&name, outlet.dtype());
            let spec = config.inputs.iter().find(|s| *s.name == *name);
            let batched = spec.and_then(|s| s.batched).unwrap_or(decl.dims.is_some());

            let mut dims = decl.dims.clone();
            if batched && let Some(all) = &decl.dims {
                match &all[0] {
                    Dim::Fixed(b) => match &fixed_batch {
                        Some((other, other_name)) if other != b => anyhow::bail!(
                            "Model inputs '{other_name}' and '{name}' have different fixed \
                                 batch sizes ({other} and {b})"
                        ),
                        Some(_) => {}
                        None => {
                            if *b == 0 {
                                anyhow::bail!("Model input '{name}' has a batch size of 0");
                            }
                            fixed_batch = Some((*b, name.clone()));
                        }
                    },
                    Dim::Dynamic(_) => {
                        if let Some(symbol) = decl.symbols.first().filter(|s| !s.is_empty()) {
                            batch_symbols.insert(symbol.clone());
                        }
                    }
                }
                dims = Some(all[1..].to_vec());
            }

            inputs.push(InputPlan {
                name,
                dtype: decl.dtype,
                type_name: decl.type_name,
                batched,
                dims,
                pad_value: spec.map_or(0.0, |s| s.pad_value),
            });
        }

        for spec in &config.inputs {
            if !inputs.iter().any(|i| *i.name == *spec.name) {
                anyhow::bail!(
                    "InputSpec for '{}' does not match any model input (inputs: {})",
                    spec.name,
                    names(inputs.iter().map(|i| &*i.name))
                );
            }
        }

        let default_input: Arc<str> = match &config.input_name {
            Some(name) => name.as_str().into(),
            None => inputs
                .first()
                .map(|i| i.name.clone())
                .context("Model has no inputs")?,
        };
        let batch_size = fixed_batch.map(|(b, _)| b);

        // Keys of the input dimensions that may be padded.
        let input_keys: HashSet<Arc<str>> = inputs
            .iter()
            .filter(|i| i.batched)
            .flat_map(|i| i.dims.iter().flatten())
            .filter_map(|d| match d {
                Dim::Dynamic(key) => Some(key.clone()),
                Dim::Fixed(_) => None,
            })
            .collect();
        let may_pad =
            !input_keys.is_empty() || inputs.iter().any(|i| i.batched && i.dims.is_none());

        let model_outputs: Vec<(Arc<str>, Declared)> = session
            .outputs()
            .iter()
            .map(|o| (Arc::<str>::from(o.name()), declared(o.name(), o.dtype())))
            .collect();
        let specs: Vec<OutputSpec> = if config.outputs.is_empty() {
            model_outputs
                .iter()
                .map(|(name, _)| OutputSpec::new(&**name))
                .collect()
        } else {
            config.outputs.clone()
        };

        let context = PlanContext {
            inputs: &inputs,
            input_keys: &input_keys,
            batch_size,
            batch_symbols: &batch_symbols,
        };
        let mut outputs = Vec::with_capacity(specs.len());
        for spec in specs {
            let decl = model_outputs
                .iter()
                .find(|(name, _)| **name == *spec.name)
                .map(|(_, d)| d);
            let plan = context.output_plan(spec, decl, &model_outputs)?;
            if let Some(problem) = &plan.problem {
                tracing::warn!("{problem}");
            } else if may_pad && !matches!(plan.split, SplitPlan::Custom(_)) {
                // Whether an unlinked axis holds padded positions would
                // otherwise only be checked per batch, when lengths happen to
                // differ, so a model could pass testing and fail under mixed
                // traffic. Ask for the relation up front instead.
                let ambiguous: Vec<usize> = match decl.and_then(|d| d.dims.as_ref()) {
                    Some(dims) => (1..dims.len())
                        .filter(|&axis| {
                            matches!(dims[axis], Dim::Dynamic(_))
                                && plan.role(axis) == AxisRole::Ambiguous
                        })
                        .collect(),
                    None => Vec::new(),
                };
                if let Some(&axis) = ambiguous.first() {
                    anyhow::bail!(
                        "Output '{}' has dynamic axes {ambiguous:?} that the model does not link \
                         to any input dimension, while inputs can be padded per batch along {}. \
                         The server cannot tell whether these axes hold padded positions that \
                         must be cut back per request. Declare each one: \
                         OutputSpec::new(\"{0}\").with_crop_axis({axis}, <input>, <input axis>) \
                         if it has one entry per position of that input dimension, or \
                         OutputSpec::new(\"{0}\").with_uncropped_axis({axis}) if it does not. \
                         If you do not need this output, select the outputs you need with \
                         ServerConfig::with_output.",
                        plan.name,
                        padded_input_axes(&inputs)
                    );
                }
            }
            outputs.push(plan);
        }

        let mut needed_outputs: Vec<Arc<str>> = Vec::new();
        for plan in &outputs {
            let mut need = |name: &Arc<str>| {
                if !needed_outputs.contains(name) {
                    needed_outputs.push(name.clone());
                }
            };
            need(&plan.name);
            if let SplitPlan::BatchIndex {
                source: Some(source),
                ..
            } = &plan.split
            {
                need(source);
            }
        }

        Ok(Self {
            inputs,
            default_input,
            batch_size,
            outputs,
            needed_outputs,
        })
    }

    /// The model's fixed batch size, if its batch dimension is not dynamic.
    pub(crate) fn batch_size(&self) -> Option<usize> {
        self.batch_size
    }

    /// Names of the outputs to read after running the model.
    pub(crate) fn needed_outputs(&self) -> &[Arc<str>] {
        &self.needed_outputs
    }

    /// Validate one request's inputs against the model.
    ///
    /// # Errors
    ///
    /// Returns an error if inputs are missing, unknown, duplicated, of the
    /// wrong element type or shape, or inconsistent along a shared dimension.
    pub(crate) fn prepare_request(&self, inputs: Inputs) -> Result<PreparedRequest> {
        let mut slots: Vec<Option<Tensor>> = vec![None; self.inputs.len()];
        for (name, tensor) in inputs.into_entries() {
            let name = name.as_deref().unwrap_or(&self.default_input);
            let idx = self
                .inputs
                .iter()
                .position(|i| &*i.name == name)
                .ok_or_else(|| {
                    anyhow::anyhow!(
                        "the model has no input named '{name}' (inputs: {})",
                        names(self.inputs.iter().map(|i| &*i.name))
                    )
                })?;
            if slots[idx].replace(tensor).is_some() {
                anyhow::bail!("input '{name}' was given more than once");
            }
        }

        let mut lengths: HashMap<Arc<str>, (usize, &str)> = HashMap::new();
        let mut tensors = Vec::with_capacity(slots.len());
        for (plan, slot) in self.inputs.iter().zip(slots) {
            let name = &*plan.name;
            let tensor = slot.ok_or_else(|| anyhow::anyhow!("missing model input '{name}'"))?;
            let Some(dtype) = plan.dtype else {
                anyhow::bail!(
                    "model input '{name}' is a {}, which is not supported",
                    plan.type_name
                );
            };
            if tensor.dtype() != dtype {
                anyhow::bail!(
                    "input '{name}' must have element type {dtype}, got {}",
                    tensor.dtype()
                );
            }
            if plan.batched {
                if let Some(dims) = &plan.dims
                    && tensor.ndim() != dims.len()
                {
                    anyhow::bail!(
                        "input '{name}' must have {} axes (without the batch axis), got shape {:?}",
                        dims.len(),
                        tensor.shape()
                    );
                }
                for (axis, (dim, &len)) in plan
                    .request_dims(&tensor)
                    .iter()
                    .zip(tensor.shape())
                    .enumerate()
                {
                    match dim {
                        Dim::Fixed(expected) if *expected != len => anyhow::bail!(
                            "input '{name}' must have length {expected} on axis {} (without the \
                             batch axis), got shape {:?}",
                            axis,
                            tensor.shape()
                        ),
                        Dim::Fixed(_) => {}
                        Dim::Dynamic(key) => match lengths.get(key) {
                            Some(&(other, other_name)) if other != len => anyhow::bail!(
                                "inputs '{other_name}' and '{name}' must have the same length \
                                 along dimension '{key}', got {other} and {len}"
                            ),
                            Some(_) => {}
                            None => {
                                lengths.insert(key.clone(), (len, name));
                            }
                        },
                    }
                }
            }
            tensors.push(tensor);
        }
        Ok(PreparedRequest { tensors })
    }

    /// Stack validated requests into batched input tensors.
    ///
    /// # Errors
    ///
    /// Returns an error if the requests cannot share a batch: different ranks
    /// for an input without a declared shape, differing values of an
    /// unbatched input, or more requests than the fixed model batch size.
    pub(crate) fn assemble(&self, requests: Vec<PreparedRequest>) -> Result<AssembledBatch> {
        let num_requests = requests.len();
        if num_requests == 0 {
            anyhow::bail!("cannot assemble an empty batch");
        }
        let rows = self.batch_size.unwrap_or(num_requests);
        if num_requests > rows {
            anyhow::bail!(
                "batch of {num_requests} requests exceeds the model's fixed batch size of {rows}"
            );
        }

        // Each request's length along every dynamic dimension.
        let mut keys: Vec<Arc<str>> = Vec::new();
        let mut lengths: HashMap<Arc<str>, Vec<usize>> = HashMap::new();
        let mut input_dims: Vec<Option<Vec<Dim>>> = Vec::with_capacity(self.inputs.len());
        for (idx, plan) in self.inputs.iter().enumerate() {
            if !plan.batched {
                input_dims.push(None);
                continue;
            }
            let dims = plan.request_dims(&requests[0].tensors[idx]);
            for (r, request) in requests.iter().enumerate() {
                let shape = request.tensors[idx].shape();
                if shape.len() != dims.len() {
                    anyhow::bail!(
                        "requests in the batch give input '{}' with different numbers of axes \
                         ({} and {})",
                        plan.name,
                        dims.len(),
                        shape.len()
                    );
                }
                for (dim, &len) in dims.iter().zip(shape) {
                    if let Dim::Dynamic(key) = dim {
                        let per_request = lengths.entry(key.clone()).or_insert_with(|| {
                            keys.push(key.clone());
                            vec![0; num_requests]
                        });
                        per_request[r] = len;
                    }
                }
            }
            input_dims.push(Some(dims));
        }
        let padded_dims: Vec<PaddedDim> = keys
            .into_iter()
            .map(|key| {
                let lengths = lengths.remove(&key).unwrap_or_default();
                PaddedDim {
                    padded: lengths.iter().copied().max().unwrap_or(0),
                    name: key,
                    lengths,
                }
            })
            .collect();

        let mut columns: Vec<Vec<Tensor>> =
            vec![Vec::with_capacity(num_requests); self.inputs.len()];
        for request in requests {
            for (idx, tensor) in request.tensors.into_iter().enumerate() {
                columns[idx].push(tensor);
            }
        }

        let mut tensors = Vec::with_capacity(self.inputs.len());
        for ((plan, dims), parts) in self.inputs.iter().zip(input_dims).zip(columns) {
            let tensor = match dims {
                None => {
                    if parts.iter().any(|t| *t != parts[0]) {
                        anyhow::bail!(
                            "input '{}' is not batched, so every request in a batch must give \
                             the same value for it",
                            plan.name
                        );
                    }
                    let first = parts.into_iter().next().expect("non-empty batch");
                    map_tensor!(first, a => a.as_standard_layout().into_owned())
                }
                Some(dims) => {
                    let target: Vec<usize> = dims
                        .iter()
                        .map(|d| match d {
                            Dim::Fixed(n) => *n,
                            Dim::Dynamic(key) => padded_dims
                                .iter()
                                .find(|p| p.name == *key)
                                .map_or(0, |p| p.padded),
                        })
                        .collect();
                    let dtype = parts[0].dtype();
                    with_element_type!(dtype, T => {
                        stack_padded::<T>(&parts, rows, &target, plan.pad_value)
                    })
                    .with_context(|| format!("failed to batch input '{}'", plan.name))?
                }
            };
            tensors.push((plan.name.clone(), tensor));
        }

        Ok(AssembledBatch {
            tensors,
            num_requests,
            rows,
            padded_dims,
        })
    }

    /// Fail early if a selected output can never be split per request.
    pub(crate) fn check_outputs(&self) -> Result<()> {
        match self.outputs.iter().find_map(|o| o.problem.as_ref()) {
            Some(problem) => Err(anyhow::Error::msg(problem.clone())),
            None => Ok(()),
        }
    }

    /// Split the raw outputs of a model run into per-request outputs.
    ///
    /// # Errors
    ///
    /// Returns an error if any selected output cannot be split per request.
    pub(crate) fn split_outputs(
        &self,
        batch: &AssembledBatch,
        raw: &HashMap<Arc<str>, Tensor>,
    ) -> Result<Vec<Outputs>> {
        self.check_outputs()?;
        let n = batch.num_requests;
        let mut per_request: Vec<Vec<(Arc<str>, Tensor)>> = (0..n)
            .map(|_| Vec::with_capacity(self.outputs.len()))
            .collect();

        for plan in &self.outputs {
            let name = &*plan.name;
            let tensor = raw
                .get(name)
                .ok_or_else(|| anyhow::anyhow!("Output tensor '{name}' not found"))?;
            let ctx = SplitContext {
                output_name: name,
                num_requests: n,
                batch_size: batch.rows,
                padded_dims: &batch.padded_dims,
                outputs: raw,
            };

            let (parts, axis_offset) = match &plan.split {
                SplitPlan::BatchAxis => (split_batch_axis(tensor, &ctx)?, Some(1)),
                SplitPlan::BatchIndex { source, column } => {
                    let index = match source {
                        Some(source) => raw.get(source).ok_or_else(|| {
                            anyhow::anyhow!("batch index output '{source}' of '{name}' not found")
                        })?,
                        None => tensor,
                    };
                    (split_by_batch_index(tensor, index, *column, &ctx)?, Some(0))
                }
                SplitPlan::Custom(split) => {
                    let parts = split(tensor, &ctx)
                        .with_context(|| format!("custom split of output '{name}' failed"))?;
                    (parts, None)
                }
            };
            if parts.len() != n {
                anyhow::bail!(
                    "Output count mismatch: splitting output '{name}' produced {} parts for {n} requests",
                    parts.len()
                );
            }

            let parts = match axis_offset {
                Some(offset) => {
                    let crops = self.crop_plan(plan, tensor, batch, offset)?;
                    parts
                        .into_iter()
                        .enumerate()
                        .map(|(r, part)| crop(part, &crops, r))
                        .collect()
                }
                None => parts,
            };
            for (outputs, part) in per_request.iter_mut().zip(parts) {
                outputs.push((plan.name.clone(), part));
            }
        }

        Ok(per_request.into_iter().map(Outputs::from_entries).collect())
    }

    /// For every axis of a per-request part, the padded dimension it follows.
    ///
    /// `offset` is the number of leading output axes the parts lack (1 when
    /// the batch axis was removed).
    fn crop_plan<'b>(
        &self,
        plan: &OutputPlan,
        tensor: &Tensor,
        batch: &'b AssembledBatch,
        offset: usize,
    ) -> Result<Vec<Option<&'b PaddedDim>>> {
        let shape = tensor.shape();
        let mut crops = Vec::with_capacity(shape.len().saturating_sub(offset));
        // Axis 0 is either the batch axis or the rows of a batch index split;
        // neither holds padded positions.
        for (axis, &len) in shape.iter().enumerate().skip(offset) {
            if axis == 0 {
                crops.push(None);
                continue;
            }
            match plan.role(axis) {
                AxisRole::Crop(key) => {
                    let dim = batch.padded_dims.iter().find(|d| d.name == key);
                    if let Some(dim) = dim
                        && dim.padded != len
                    {
                        anyhow::bail!(
                            "output '{}' axis {axis} follows dimension '{key}', which was \
                                 padded to {} in this batch, but has length {len}",
                            plan.name,
                            dim.padded
                        );
                    }
                    crops.push(dim);
                }
                AxisRole::Independent => crops.push(None),
                AxisRole::Ambiguous => {
                    if let Some(dim) = batch
                        .padded_dims
                        .iter()
                        .find(|d| d.padded == len && d.lengths.iter().any(|&l| l < d.padded))
                    {
                        anyhow::bail!(
                            "output '{}' axis {axis} has length {len}, the length dimension \
                             '{}' was padded to in this batch, but the model does not say \
                             whether it follows that dimension, so padded positions could \
                             reach callers; declare it with \
                             OutputSpec::with_crop_axis({axis}, <input>, <input axis>) or \
                             OutputSpec::with_uncropped_axis({axis})",
                            plan.name,
                            dim.name
                        );
                    }
                    crops.push(None);
                }
            }
        }
        Ok(crops)
    }
}

/// What the plan builder needs to know about the inputs.
struct PlanContext<'a> {
    inputs: &'a [InputPlan],
    input_keys: &'a HashSet<Arc<str>>,
    batch_size: Option<usize>,
    batch_symbols: &'a HashSet<String>,
}

impl PlanContext<'_> {
    fn output_plan(
        &self,
        spec: OutputSpec,
        decl: Option<&Declared>,
        model_outputs: &[(Arc<str>, Declared)],
    ) -> Result<OutputPlan> {
        let name: Arc<str> = spec.name.as_str().into();
        let explicit_split = spec.split.is_some();
        let split = match spec.split {
            None | Some(Split::BatchAxis) => SplitPlan::BatchAxis,
            Some(Split::BatchIndex { source, column }) => SplitPlan::BatchIndex {
                source: source.map(|s| s.as_str().into()),
                column,
            },
            Some(Split::Custom(f)) => SplitPlan::Custom(f),
        };

        let mut problem = None;
        let mut roles = HashMap::new();

        let mut set_problem = |message: String| {
            if problem.is_none() {
                problem = Some(message);
            }
        };

        match decl {
            None => set_problem(format!(
                "Output tensor '{name}' not found in the model (outputs: {})",
                names(model_outputs.iter().map(|(n, _)| &**n))
            )),
            Some(decl) => {
                if decl.dtype.is_none() {
                    set_problem(format!(
                        "output '{name}' is a {}, which is not supported",
                        decl.type_name
                    ));
                }
                if let SplitPlan::BatchAxis = split
                    && let Some(message) = self.batch_axis_problem(&name, decl, explicit_split)
                {
                    set_problem(message);
                }
                if let Some(dims) = &decl.dims {
                    for (axis, dim) in dims.iter().enumerate().skip(1) {
                        let role = match dim {
                            Dim::Fixed(_) => AxisRole::Independent,
                            Dim::Dynamic(key) if self.input_keys.contains(key) => {
                                AxisRole::Crop(key.clone())
                            }
                            Dim::Dynamic(_) => {
                                let symbol = decl.symbols.get(axis).map_or("", String::as_str);
                                if is_generated_symbol(symbol) {
                                    AxisRole::Ambiguous
                                } else {
                                    AxisRole::Independent
                                }
                            }
                        };
                        roles.insert(axis, role);
                    }
                }
            }
        }

        if let SplitPlan::BatchIndex {
            source: Some(source),
            ..
        } = &split
            && !model_outputs.iter().any(|(n, _)| n == source)
        {
            set_problem(format!(
                "batch index output '{source}' of '{name}' not found in the model"
            ));
        }

        for axis in &spec.uncropped_axes {
            roles.insert(*axis, AxisRole::Independent);
        }
        for crop in &spec.crop_axes {
            if crop.axis == 0 {
                anyhow::bail!(
                    "OutputSpec for '{name}': axis 0 is the batch axis and cannot be cropped"
                );
            }
            let input = self
                .inputs
                .iter()
                .find(|i| *i.name == *crop.input && i.batched)
                .ok_or_else(|| {
                    anyhow::anyhow!(
                        "OutputSpec for '{name}': '{}' is not a batched model input",
                        crop.input
                    )
                })?;
            if crop.input_axis == 0 {
                anyhow::bail!(
                    "OutputSpec for '{name}': input axis 0 is the batch axis, not a padded dimension"
                );
            }
            let key = match &input.dims {
                Some(dims) => match dims.get(crop.input_axis - 1) {
                    Some(Dim::Dynamic(key)) => key.clone(),
                    Some(Dim::Fixed(_)) => anyhow::bail!(
                        "OutputSpec for '{name}': axis {} of input '{}' has a fixed size, so it \
                         is never padded",
                        crop.input_axis,
                        crop.input
                    ),
                    None => anyhow::bail!(
                        "OutputSpec for '{name}': input '{}' has no axis {}",
                        crop.input,
                        crop.input_axis
                    ),
                },
                None => dim_key(&input.name, crop.input_axis),
            };
            roles.insert(crop.axis, AxisRole::Crop(key));
        }

        Ok(OutputPlan {
            name,
            split,
            roles,
            problem,
        })
    }

    /// Why axis 0 of an output is known not to be the batch axis, if it is.
    fn batch_axis_problem(&self, name: &str, decl: &Declared, explicit: bool) -> Option<String> {
        let dims = decl.dims.as_ref()?;
        let advice = "configure a different Split for it (e.g. Split::BatchIndex or \
                      Split::Custom) or select only the outputs you need with \
                      ServerConfig::with_output";
        let batch = match self.batch_size {
            Some(b) => format!("the model's batch size is fixed at {b}"),
            None => "the model's batch dimension is dynamic".to_string(),
        };
        match &dims[0] {
            Dim::Fixed(d) if Some(*d) != self.batch_size => Some(format!(
                "Output count mismatch: output '{name}' has a fixed size of {d} on axis 0 while \
                 {batch}, so axis 0 is not one entry per request; {advice}"
            )),
            Dim::Fixed(_) => None,
            Dim::Dynamic(_) if explicit => None,
            Dim::Dynamic(_) if self.batch_size.is_some() => Some(format!(
                "Output count mismatch: output '{name}' has a dynamic size on axis 0 while \
                 {batch}, so its length is data-dependent rather than one entry per request; \
                 {advice}. If axis 0 really is the batch axis, set Split::BatchAxis explicitly"
            )),
            Dim::Dynamic(_) => {
                let symbol = decl.symbols.first().map_or("", String::as_str);
                let named_differently = !is_generated_symbol(symbol)
                    && !self.batch_symbols.is_empty()
                    && !self.batch_symbols.contains(symbol);
                named_differently.then(|| {
                    let mut batch_names: Vec<&str> =
                        self.batch_symbols.iter().map(String::as_str).collect();
                    batch_names.sort_unstable();
                    format!(
                        "Output count mismatch: output '{name}' axis 0 is the dimension \
                         '{symbol}', not the inputs' batch dimension '{}', so it is not one \
                         entry per request; {advice}. If axis 0 really is the batch axis, set \
                         Split::BatchAxis explicitly",
                        batch_names.join("', '")
                    )
                })
            }
        }
    }
}

fn names<'a>(names: impl Iterator<Item = &'a str>) -> String {
    names.collect::<Vec<_>>().join(", ")
}

/// The input axes that can be padded, for errors: `'input_ids' axis 1, ...`.
fn padded_input_axes(inputs: &[InputPlan]) -> String {
    let mut axes = Vec::new();
    for input in inputs.iter().filter(|i| i.batched) {
        match &input.dims {
            Some(dims) => axes.extend(
                dims.iter()
                    .enumerate()
                    .filter(|(_, d)| matches!(d, Dim::Dynamic(_)))
                    .map(|(axis, _)| format!("'{}' axis {}", input.name, axis + 1)),
            ),
            None => axes.push(format!("every axis of '{}'", input.name)),
        }
    }
    axes.join(", ")
}

/// Stack per-request arrays along a new axis 0 into `rows` rows of shape
/// `target`, filling the gaps (shorter requests, extra rows) with `pad`.
fn stack_padded<T: Element>(
    parts: &[Tensor],
    rows: usize,
    target: &[usize],
    pad: f64,
) -> Result<Tensor> {
    let arrays: Vec<&ArrayD<T>> = parts
        .iter()
        .map(|t| {
            T::as_array(t).ok_or_else(|| {
                anyhow::anyhow!(
                    "element types differ within the batch ({} and {})",
                    T::TYPE,
                    t.dtype()
                )
            })
        })
        .collect::<Result<_>>()?;

    if rows == arrays.len() && arrays.iter().all(|a| a.shape() == target) {
        let views: Vec<_> = arrays.iter().map(|a| a.view()).collect();
        return Ok(T::wrap(ndarray::stack(Axis(0), &views)?));
    }

    let mut shape = Vec::with_capacity(target.len() + 1);
    shape.push(rows);
    shape.extend_from_slice(target);
    let mut out = ArrayD::from_elem(IxDyn(&shape), T::from_f64(pad));
    for (row, array) in arrays.iter().enumerate() {
        if array.ndim() != target.len() || array.shape().iter().zip(target).any(|(l, t)| l > t) {
            anyhow::bail!(
                "request shape {:?} does not fit the batch shape {target:?}",
                array.shape()
            );
        }
        let mut dst = out.index_axis_mut(Axis(0), row);
        dst.slice_each_axis_mut(|ax| Slice::from(0..array.shape()[ax.axis.index()]))
            .assign(*array);
    }
    Ok(T::wrap(out))
}

/// Cut a per-request part back to request `request`'s own lengths.
fn crop(part: Tensor, crops: &[Option<&PaddedDim>], request: usize) -> Tensor {
    let limits: Vec<Option<usize>> = crops
        .iter()
        .map(|c| {
            c.map(|d| d.lengths[request])
                .filter(|&l| Some(l) != c.map(|d| d.padded))
        })
        .collect();
    if limits.iter().all(Option::is_none) || limits.len() != part.ndim() {
        return part;
    }
    map_tensor!(part, a => a
        .slice_each_axis(|ax| match limits[ax.axis.index()] {
            Some(len) => Slice::from(0..len),
            None => Slice::from(..),
        })
        .to_owned())
}

/// Copy an ONNX Runtime output value into a [`Tensor`].
pub(crate) fn tensor_from_ort(name: &str, value: &DynValue) -> Result<Tensor> {
    let dtype = match value.dtype() {
        ValueType::Tensor { ty, .. } => ElementType::from_ort(*ty).ok_or_else(|| {
            anyhow::anyhow!("output '{name}' has element type {ty}, which is not supported")
        })?,
        other => anyhow::bail!("output '{name}' is a {other:?}, which is not supported"),
    };
    with_element_type!(dtype, T => {
        let (shape, data) = value.try_extract_tensor::<T>()?;
        let shape: Vec<usize> = shape.iter().map(|&d| d as usize).collect();
        Ok(T::wrap(ArrayD::from_shape_vec(IxDyn(&shape), data.to_vec())?))
    })
}

/// Borrow a batched input tensor as an ONNX Runtime session input.
pub(crate) fn session_input(tensor: &Tensor) -> Result<ort::session::SessionInputValue<'_>> {
    visit_tensor!(tensor, a => Ok(ort::value::TensorRef::from_array_view(a.view())?
        .into_dyn()
        .into()))
}
